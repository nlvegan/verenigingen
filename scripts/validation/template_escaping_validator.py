#!/usr/bin/env python3
"""Hard gate: every ``{{ ... }}`` in a portal page or email template must be escaped (#1890).

## The mechanism

Frappe renders website page templates AND email templates through the same
``frappe.get_jenv()`` environment, and that environment has ``autoescape`` OFF.
Measured on test_site_9 (2026-10-31, #1890): ``frappe.render_template("{{ x }} |
{{ x|e }}", {"x": "<b>x</b>"})`` gave ``<b>x</b> | &lt;b&gt;x&lt;/b&gt;``, and
``get_template("verenigingen/templates/pages/chapter_dashboard.html").environment
.autoescape`` is ``False``. So a bare ``{{ member.full_name }}`` prints whatever an
applicant typed, as markup. That is stored XSS wherever the viewer is someone other than
the author (a board member reading an applicant's name).

## The rule

Every output expression must END in one of:

* ``|e`` / ``|escape`` / ``|forceescape``;
* ``|tojson`` (the jinja filter escapes ``< > & '``, so it is safe in a script block;
  ``|tojson|safe`` is accepted for the same reason);
* a numeric coercion (``|int``, ``|float``, ``|abs``, ``|length``, ``|count``);
* ``|safe`` ONLY when an ``|e`` / ``|tojson`` earlier in the same chain already escaped it.

or be:

* a literal (a string or number);
* ``_("literal string")`` -- the translated string is source code, not user input;
* ``super()``;
* a conditional or ``or``/``and`` whose every branch is one of the above.

Anything else needs an entry in ``ALLOWED_CALLS`` / ``ALLOWED_EXPRESSIONS`` with a reason.
``_("... {0}").format(x)`` does NOT qualify: ``x`` reaches the page unescaped. End the whole
expression in ``|e`` instead.

## Scope

``verenigingen/templates/**/*.html`` (pages, emails, includes, macros, donation, the base
portal template), plus ``verenigingen/www/*.html`` and
``verenigingen/verenigingen_payments/templates/**/*.html`` (#1897: same jenv, same autoescape-off).
The Mollie checkout page and the three SEPA mandate emails live in the latter. Jinja comments and ``{% raw %}`` blocks are skipped by the lexer, which
is why this uses jinja2's own tokenizer rather than a regex.

## Not covered (deliberately)

* ``.py`` code that builds HTML strings.
* Context: ``|e`` is HTML-escaping. Inside a JS string it blocks a ``</script>`` or a quote
  breakout but not a backslash; use ``|tojson`` for a value placed in JS source.

## URL schemes (#2884)

``|e`` in an ``href``/``src``/``action`` does not stop a ``javascript:`` scheme. When an expression
BEGINS such an attribute value it must also pass through ``|safe_url``
(``verenigingen/utils/jinja_safe_url.py``: http/https/mailto/relative allowlist), or be listed in
``URL_ATTR_BASELINE`` with the reason its value cannot be set by a non-staff user. The baseline
holds the sites traced to a server-built URL or a staff-only field (#2884); a NEW site is refused
until it uses the filter or is traced and added.

## chapter_dashboard.html

Branch ``feat/1765-application-record`` also escapes this file, partly. The gate covers the
file on develop, so that merge has to take the stricter of the two sides.

Usage: ``python scripts/validation/template_escaping_validator.py [file ...]`` (no
arguments scans the whole tree). Exit 1 on any finding.
"""

