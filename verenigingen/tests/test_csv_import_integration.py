"""
Integration Tests for CSV Import with Enhanced Test Factory

Tests complete CSV import workflow using realistic Dutch association data
generated by EnhancedTestCase fixtures.
"""

import csv
import os
import tempfile

import frappe
from frappe.tests.utils import FrappeTestCase

from verenigingen.tests.fixtures.enhanced_test_factory import EnhancedTestCase
from verenigingen.utils.csv.secure_csv_parser import SecureCSVParser


class TestCSVImportIntegration(EnhancedTestCase):
	"""Integration tests for CSV import with realistic test data"""

	def setUp(self):
		"""Set up test environment with realistic data"""
		super().setUp()
		self.parser = SecureCSVParser()
		self.temp_files = []

	def tearDown(self):
		"""Clean up temporary CSV files"""
		for temp_file in self.temp_files:
			if os.path.exists(temp_file):
				try:
					os.unlink(temp_file)
				except OSError:
					pass
		super().tearDown()

	def _create_temp_csv(self, data, suffix='.csv'):
		"""Create temporary CSV file with test data"""
		temp_file = tempfile.NamedTemporaryFile(
			mode='w',
			suffix=suffix,
			delete=False,
			encoding='utf-8'
		)

		if data:
			writer = csv.DictWriter(temp_file, fieldnames=data[0].keys())
			writer.writeheader()
			writer.writerows(data)

		temp_file.close()
		self.temp_files.append(temp_file.name)
		return temp_file.name

	def test_import_dutch_members_with_tussenvoegsel(self):
		"""Test importing Dutch members with name particles (tussenvoegsel)"""
		csv_data = [
			{
				"first_name": "Jan",
				"tussenvoegsel": "van",
				"last_name": "Dijk",
				"email": "jan.van.dijk@example.com",
				"birth_date": "1985-05-15",
				"postal_code": "1012 AB",
				"city": "Amsterdam"
			},
			{
				"first_name": "Maria",
				"tussenvoegsel": "de",
				"last_name": "Jong",
				"email": "maria.de.jong@example.com",
				"birth_date": "1990-08-22",
				"postal_code": "3011 CD",
				"city": "Rotterdam"
			}
		]

		temp_file = self._create_temp_csv(csv_data)
		result = self.parser._read_file_from_path(temp_file)

		self.assertEqual(len(result), 2)
		self.assertEqual(result[0]["first_name"], "Jan")
		self.assertEqual(result[0]["tussenvoegsel"], "van")
		self.assertEqual(result[0]["last_name"], "Dijk")
		self.assertEqual(result[1]["tussenvoegsel"], "de")

