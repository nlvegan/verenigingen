	def test_import_utf8_with_bom(self):
		"""Test importing UTF-8 CSV with BOM (common from Windows Excel)"""
		# Don't include BOM in the content string - utf-8-sig encoding handles it
		csv_content = "name,city\nJohán,Arnhem\nMariël,Utrecht\n"

		temp_file = tempfile.NamedTemporaryFile(
			mode='w',
			suffix='.csv',
			delete=False,
			encoding='utf-8-sig'
		)
		temp_file.write(csv_content)
		temp_file.close()
		self.temp_files.append(temp_file.name)

		result = self.parser._read_file_from_path(temp_file.name)

		self.assertEqual(len(result), 2)
		# BOM should be stripped by utf-8-sig encoding (tried first in encoding list)
		self.assertIn("name", result[0])
		self.assertEqual(result[0]["name"], "Johán")

