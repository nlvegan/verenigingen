	def test_import_with_empty_and_null_values(self):
		"""Test importing CSV with various empty/null indicators"""
		csv_data = [
			{"name": "Member 1", "email": "test@example.com", "phone": "-"},
			{"name": "Member 2", "email": "-", "phone": "0612345678"},
			{"name": "Member 3", "email": "N/A", "phone": "NB"},
		]

		temp_file = self._create_temp_csv(csv_data)
		result = self.parser._read_file_from_path(temp_file)

		self.assertEqual(len(result), 3)
		# Parser cleans "-" and "NB" to None (per parse_csv_content logic)
		self.assertIsNone(result[0]["phone"])
		self.assertIsNone(result[1]["email"])
		# N/A is NOT cleaned by parser - that happens in data_transformers.clean_value()
		self.assertEqual(result[2]["email"], "N/A")
		self.assertIsNone(result[2]["phone"])

