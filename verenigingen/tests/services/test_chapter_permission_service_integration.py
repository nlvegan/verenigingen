    @classmethod
    def tearDownClass(cls):
        """Clean up test data after all tests"""
        # Clean up in reverse order of dependencies
        try:
            # Delete users created by tests
            for email in cls._created_users:
                if frappe.db.exists("User", email):
                    frappe.delete_doc("User", email, force=True, ignore_permissions=True)

            # Delete volunteers
            for name in cls._created_volunteers:
                if frappe.db.exists("Volunteer", name):
                    frappe.delete_doc("Volunteer", name, force=True, ignore_permissions=True)

            # Delete members and their customers
            for name in cls._created_members:
                if frappe.db.exists("Member", name):
                    member = frappe.get_doc("Member", name)
                    customer = member.customer
                    frappe.delete_doc("Member", name, force=True, ignore_permissions=True)
                    if customer and frappe.db.exists("Customer", customer):
                        frappe.delete_doc("Customer", customer, force=True, ignore_permissions=True)

            # Delete chapters
            for name in cls._created_chapters:
                if frappe.db.exists("Chapter", name):
                    frappe.delete_doc("Chapter", name, force=True, ignore_permissions=True)

            frappe.db.commit()
        except Exception as e:
            frappe.log_error(f"Cleanup error in TestChapterPermissionServiceIntegration: {str(e)}")

        if hasattr(cls, '_test_instance'):
            cls._test_instance.tearDown()
        super().tearDownClass()

    def setUp(self):
        """Set up before each test - clean roles to prevent cross-test pollution.

        IMPORTANT: Role Cleanup Rationale
        ---------------------------------
        Frappe's permission system exhibits cross-test role pollution where additional
        roles (e.g., System Manager, Verenigingen Administrator) can be added to test
        users between test methods. This occurs due to:

        1. Role caching in frappe.get_roles() via Redis (frappe.cache.hget("roles", user))
        2. Hooks like assign_chapter_board_role() that trigger on document saves
        3. Test framework interactions with the permission system

        Without this cleanup, tests that depend on a user having ONLY a specific role
        (like testing that a board member is DENIED access to other chapters) will fail
        because the user unexpectedly has admin roles.

        The _reset_user_roles() method uses direct SQL to bypass caching issues with
        Frappe's add_roles() method, ensuring deterministic test state.
        """
        super().setUp()

        # Reset all test users to their intended single role before each test
        self._reset_user_roles("admin.test@verenigingen.test", "System Manager")
        self._reset_user_roles("board.test@verenigingen.test", "Verenigingen Chapter Board Member")
        self._reset_user_roles("regular.test@verenigingen.test", "Verenigingen Member")
        frappe.db.commit()

    @staticmethod
    def _get_db_roles(user):
        """Get actual roles from database, bypassing frappe.get_roles() caching.

        In test mode, frappe.get_roles() can return incorrect results due to
        role caching and test framework interactions. This method queries the
        Has Role table directly for accurate test assertions.
        """
        db_roles = frappe.db.sql("""
            SELECT role FROM `tabHas Role`
            WHERE parent = %s AND parenttype = 'User'
        """, user, as_list=True)
        roles = [r[0] for r in db_roles]
        # Add implicit roles
        roles.extend(["All", "Guest"])
        return roles

    @classmethod
    def _create_board_membership_class(cls, chapter_name, volunteer_name, role):
        """Class-level helper to create board membership"""
        chapter_doc = frappe.get_doc("Chapter", chapter_name)
        chapter_doc.append("board_members", {
            "volunteer": volunteer_name,
            "chapter_role": role,
            "from_date": today(),
            "is_active": 1
        })
        chapter_doc.save()

    @classmethod
    def _create_test_user_with_role_class(cls, email, role):
        """Class-level helper to create test user with specific role.

        Uses direct SQL to avoid caching issues with add_roles() which can
        re-save cached roles from previous test runs.
        """
        if frappe.db.exists("User", email):
            # User exists - clear ALL roles (except system ones) using direct SQL
            frappe.db.sql("""
                DELETE FROM `tabHas Role`
                WHERE parent = %s AND parenttype = 'User'
            """, email)

            # Add the specific role using direct SQL to avoid cache issues
            frappe.db.sql("""
                INSERT INTO `tabHas Role` (name, parent, parenttype, parentfield, role)
                VALUES (%s, %s, 'User', 'roles', %s)
            """, (frappe.generate_hash(length=10), email, role))

            # Clear role cache for this user
            frappe.cache.hdel("roles", email)
            frappe.db.commit()
        else:
            user = frappe.get_doc({
                "doctype": "User",
                "email": email,
                "first_name": email.split("@")[0].split(".")[0].title(),
                "enabled": 1,
                "send_welcome_email": 0
            })
            user.insert(ignore_permissions=True)  # OK in test setup

            # Add role via direct SQL to avoid any caching
            frappe.db.sql("""
                INSERT INTO `tabHas Role` (name, parent, parenttype, parentfield, role)
                VALUES (%s, %s, 'User', 'roles', %s)
            """, (frappe.generate_hash(length=10), email, role))

            frappe.cache.hdel("roles", email)
            cls._created_users.append(email)

    @classmethod
    def _reset_user_roles(cls, email, role):
        """Reset a user's roles to just the specified role.

        Called AFTER all setup hooks have run to ensure clean role state.
        Uses direct SQL to avoid any caching or doc-level behavior.
        """
        # Delete ALL existing roles
        frappe.db.sql("""
            DELETE FROM `tabHas Role`
            WHERE parent = %s AND parenttype = 'User'
        """, email)

        # Insert just the specified role
        frappe.db.sql("""
            INSERT INTO `tabHas Role` (name, parent, parenttype, parentfield, role)
            VALUES (%s, %s, 'User', 'roles', %s)
        """, (frappe.generate_hash(length=10), email, role))

        # Clear role cache
        frappe.cache.hdel("roles", email)

    def _create_test_user_with_role(self, email, role):
        """Helper to create test user with specific role"""
        if not frappe.db.exists("User", email):
            user = frappe.get_doc({
                "doctype": "User",
                "email": email,
                "first_name": email.split("@")[0].split(".")[0].title(),
                "enabled": 1,
                "send_welcome_email": 0
            })
            user.insert(ignore_permissions=True)  # OK in test setup
            user.add_roles(role)
            self._created_users.append(email)
            frappe.db.commit()  # Commit so user exists in test

