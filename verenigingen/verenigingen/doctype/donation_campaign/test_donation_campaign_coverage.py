    # ------------------------------------------------------------------
    # module-level update_campaign_progress()
    # ------------------------------------------------------------------
    def test_module_update_campaign_progress_aggregates(self):
        from verenigingen.verenigingen.doctype.donation_campaign.donation_campaign import (
            update_campaign_progress,
        )

        campaign = self._make_campaign(monetary_goal=500, donor_goal=2)
        d1 = self._make_donor()
        d2 = self._make_donor()
        self._make_paid_donation(campaign.name, d1, 100)
        self._make_paid_donation(campaign.name, d2, 150, anonymous=0)

        with self.assertNoErrorLog():
            update_campaign_progress(campaign.name)

        campaign.reload()
        self.assertEqual(campaign.total_donations, 2)
        self.assertEqual(campaign.total_raised, 250)
        self.assertEqual(campaign.total_donors, 2)
        self.assertEqual(campaign.monetary_progress, 50.0)  # 250/500
        self.assertEqual(campaign.donor_progress, 100.0)  # 2/2

    def test_module_update_campaign_progress_excludes_anonymous_from_donor_count(self):
        """Anonymous paid donations count toward totals/raised but NOT unique donors."""
        from verenigingen.verenigingen.doctype.donation_campaign.donation_campaign import (
            update_campaign_progress,
        )

        campaign = self._make_campaign()
        d1 = self._make_donor()
        d2 = self._make_donor()
        self._make_paid_donation(campaign.name, d1, 100, anonymous=0)
        self._make_paid_donation(campaign.name, d2, 100, anonymous=1)

        update_campaign_progress(campaign.name)
        campaign.reload()
        self.assertEqual(campaign.total_donations, 2)
        self.assertEqual(campaign.total_raised, 200)
        # Anonymous donor excluded from DISTINCT donor count -> only 1.
        self.assertEqual(campaign.total_donors, 1)
